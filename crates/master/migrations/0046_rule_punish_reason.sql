-- Формулировка наказания у пункта свода.
--
-- Модератор в игре чаще всего называет только пункт: `/mute Steve 30m 1.1`.
-- Причину до сих пор собирал агент из общего шаблона — «Нарушение п.1.1:
-- <заголовок>», — и заголовок пункта в неё попадал целиком: «Уважение к другим
-- игрокам». В бане это читается как похвала, а не как причина.
--
-- Поэтому у правила появляется своя строка: «Оскорбление участников»,
-- «Использование сторонних программ». Она локализуется вместе с остальным
-- сводом, потому что её видит игрок, а не администратор.
--
-- Пусто — прежнее поведение: причина собирается из шаблона `reason_by_rule`.

ALTER TABLE rules ADD COLUMN IF NOT EXISTS punish_reason TEXT NOT NULL DEFAULT '';
ALTER TABLE rule_translations ADD COLUMN IF NOT EXISTS punish_reason TEXT NOT NULL DEFAULT '';
