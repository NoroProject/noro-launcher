-- Префикс и суффикс роли — то, что стоит вокруг ника в игре.
--
-- До сих пор префиксом работала иконка (`icon`), и это было подменой понятий:
-- иконка — один глиф рядом с ником и в списке ролей на сайте, а префикс —
-- произвольная строка вроде `&8[&cADMIN&8]`, которую владелец сервера пишет
-- сам. Совместить их в одном поле нельзя: иконка обязана оставаться коротким
-- символом, чтобы влезать в таб и в шапку профиля.
--
-- Значения хранятся с амперсандом (`&c`), а не с `§`: их набирают руками в
-- админке, и знак параграфа с клавиатуры не ввести. В `§` их переводит агент,
-- там же, где раскрашивает тексты наказаний.
--
-- Существующие роли остаются с пустыми полями: пока префикс не задан, агент
-- по-прежнему показывает иконку в цвете роли — иначе обновление молча сняло бы
-- префиксы у всех сразу.

ALTER TABLE roles ADD COLUMN IF NOT EXISTS prefix TEXT;
ALTER TABLE roles ADD COLUMN IF NOT EXISTS suffix TEXT;
