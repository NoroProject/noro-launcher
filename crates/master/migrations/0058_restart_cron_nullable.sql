-- `restart_schedules.cron_expr` должна быть необязательной.
--
-- Первая редакция 0051 объявила её `NOT NULL`, и на базах, прошедших через неё,
-- ограничение осталось: `ADD COLUMN IF NOT EXISTS` из 0055 к уже существующей
-- колонке не применяется. На свежей установке колонка nullable — то есть dev и
-- прод расходятся в том, какие расписания вообще можно завести.
--
-- Расписание задаётся одним из трёх способов: `at_times`, `interval_minutes`
-- или cron. Требовать при этом cron значит запретить два первых — а именно они
-- и есть «простой конструктор», ради которого сырой cron оставлен на редкие
-- случаи.
--
-- Замечено сравнением схемы dev с той, что собирается прогоном всех миграций на
-- пустой базе: по именам колонок расхождения не видно, оно только в nullability.
ALTER TABLE restart_schedules ALTER COLUMN cron_expr DROP NOT NULL;
