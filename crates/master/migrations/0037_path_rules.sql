-- Единый упорядоченный список правил вместо трёх независимых списков.
--
-- Побеждает последнее совпавшее правило, как в .gitignore: исключение пишется
-- строкой ниже, а не выносится в отдельный массив с неочевидным приоритетом.
--
-- NULL, а не пустой массив: пустой означал бы «правил нет», а нам нужно
-- отличать это от «правила ещё не заданы» — тогда они выводятся из старых
-- списков, которые остаются на месте.
ALTER TABLE builds ADD COLUMN IF NOT EXISTS path_rules JSONB;
