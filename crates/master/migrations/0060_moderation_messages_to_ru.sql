-- Старые шаблоны наказаний переезжают в русский набор.
--
-- До словаря по языкам `moderation_messages` хранил один плоский объект, и
-- умолчания в нём были русскими — тексты в базе тоже. С появлением словаря
-- этот объект стал читаться как английский набор: русский игрок получал
-- нетронутые умолчания вместо набранных в админке текстов, а англоязычный —
-- русский экран бана.
--
-- Плюс набор с тех пор вырос с девяти полей до семнадцати, и недостающие
-- добирались английскими умолчаниями даже в русском наборе. Это чинится в
-- коде (`merge` дополняет умолчаниями своего языка), а здесь — только форма
-- хранения.
--
-- Идемпотентно: признак старого формата — `ban_permanent` на верхнем уровне,
-- у нового там ключи языков.
UPDATE instance_settings
SET value = jsonb_build_object('ru', value)
WHERE key = 'moderation_messages'
  AND value ? 'ban_permanent';
