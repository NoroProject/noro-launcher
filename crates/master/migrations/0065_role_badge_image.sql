-- Своя картинка плашки роли.
--
-- Нарисованная нами плашка подходит не всем: у роли может быть свой знак,
-- который шрифтом 5×7 не набрать. Здесь ссылка на файл в хранилище — сам файл
-- лежит рядом с остальными и раздаётся тем же `/files/{sha1}`.
--
-- Пусто значит «рисовать самим»: снимать картинку — это просто очистить поле.
-- IF NOT EXISTS: колонку могли добавить руками при отладке, и падать из-за
-- этого на старте мастера незачем — результат один и тот же.
ALTER TABLE roles ADD COLUMN IF NOT EXISTS badge_sha1 TEXT;
