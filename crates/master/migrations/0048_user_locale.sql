-- Язык игрока: фолбэк для сообщений, когда язык клиента ещё не известен.
--
-- Внутри игры язык берётся у самого клиента, но на экране отказа при входе его
-- ещё нет: игрок до мира не дошёл, и `ClientInformation` мастеру не досталось.
-- Ровно там причина бана и нужна понятной — иначе забаненный русский игрок
-- читает по-английски в единственный момент, когда ему важно понять текст.
--
-- NULL — «не выбирал»: тогда работает язык по умолчанию (`en`), а не пустая
-- строка, по которой не отличить «выбрал английский» от «не выбирал».
ALTER TABLE users ADD COLUMN IF NOT EXISTS locale TEXT;
