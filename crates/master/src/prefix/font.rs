/// Глиф буквы. Неизвестный символ рисуется пробелом: чужой алфавит в названии
/// роли не должен ронять сборку пака, а дыра в плашке видна и сама.
fn glyph(ch: char) -> Glyph {
    let upper = ch.to_uppercase().next().unwrap_or(ch);
    GLYPHS
        .iter()
        .find(|(c, _, _)| *c == upper)
        .copied()
        .unwrap_or((' ', 3, [0; HEIGHT]))
}

/// Ширина строки в пикселях — столько же займёт готовая плашка без полей.
pub fn width(text: &str) -> usize {
    text.chars().map(|c| glyph(c).1).sum()
}

/// Пробегает точки букв: `(x, y)` каждого зажжённого пикселя.
pub fn dots(text: &str, mut at: impl FnMut(usize, usize)) {
    let mut x = 0;
    for ch in text.chars() {
        let (_, advance, rows) = glyph(ch);
        for (y, row) in rows.iter().enumerate() {
            for col in 0..CELL {
                if row & (1 << (CELL - 1 - col)) != 0 {
                    at(x + col, y);
                }
            }
        }
        x += advance;
    }
}
