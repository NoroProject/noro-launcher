use super::*;
use std::collections::HashSet;

/// Два вида отказа с одним номером — это скриншот от игрока, по которому нельзя
/// сказать, что произошло. Реестр держится макросом, но дубль в нём написать
/// по-прежнему можно, поэтому проверяем.
#[test]
fn номера_уникальны() {
    let mut seen = HashSet::new();
    for c in ALL {
        assert!(seen.insert(c.number), "номер {} занят дважды", c.number);
    }
}

#[test]
fn слаги_уникальны() {
    let mut seen = HashSet::new();
    for c in ALL {
        assert!(seen.insert(c.slug), "слаг {} занят дважды", c.slug);
    }
}

/// Номер обязан попадать в объявленный диапазон: по первой цифре видно, про что
/// отказ, и это единственное, что можно понять, не заглядывая в реестр.
#[test]
fn номера_лежат_в_своих_диапазонах() {
    for c in ALL {
        let group = c.number / 100;
        assert!(
            matches!(group, 10 | 11 | 12 | 13 | 14 | 19),
            "{} ({}) вне диапазонов реестра",
            c.number,
            c.slug
        );
    }
}

/// Слаг — то, по чему ветвится код клиента, поэтому он остаётся машинным:
/// нижний регистр, подчёркивания, без пробелов.
#[test]
fn слаги_машинные() {
    for c in ALL {
        assert!(
            c.slug
                .chars()
                .all(|ch| ch.is_ascii_lowercase() || ch == '_'),
            "слаг {} не машинный",
            c.slug
        );
    }
}
