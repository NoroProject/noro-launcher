//! Одноразовый билет на скачивание архива.
//!
//! Ручка закрыта правом, а право проверяется по заголовку `Authorization` —
//! которого обычная навигация браузера не носит. Из-за этого админка качала
//! архив через `fetch` и складывала его в память вкладки: на паре гигабайт это
//! минуты ожидания и вкладка на грани падения. Safari вдобавок не умеет
//! `showSaveFilePicker`, так что запасной ветки без памяти там нет.
//!
//! Билет разрывает этот узел: право проверяется один раз при выдаче, а сам файл
//! отдаётся по ссылке, которую браузер скачивает сам — потоком на диск, со
//! своим индикатором и без единого байта в JS.
//!
//! Живёт в памяти процесса. Второй инстанс билета не увидит, но цена ошибки —
//! отказ и повторное нажатие, а не потерянный доступ.

use dashmap::DashMap;
use once_cell::sync::Lazy;
use std::time::{Duration, Instant};
use uuid::Uuid;

/// Билет живёт ровно столько, сколько нужно на переход по ссылке.
const TTL: Duration = Duration::from_secs(120);

static TICKETS: Lazy<DashMap<Uuid, Instant>> = Lazy::new(DashMap::new);

/// Выдать билет. Заодно выметает просроченные: отдельная уборка ради записи в
/// пару десятков байт не нужна.
pub fn issue() -> Uuid {
    TICKETS.retain(|_, issued| issued.elapsed() < TTL);
    let id = Uuid::new_v4();
    TICKETS.insert(id, Instant::now());
    id
}

/// Погасить билет. Второй раз тот же билет не сработает: ссылка оседает в
/// истории браузера и в логах прокси, и одноразовость — единственное, что
/// мешает ей стать постоянным ключом от всей базы.
pub fn consume(id: Uuid) -> bool {
    match TICKETS.remove(&id) {
        Some((_, issued)) => issued.elapsed() < TTL,
        None => false,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn билет_срабатывает_ровно_один_раз() {
        let id = issue();
        assert!(consume(id), "свежий билет должен приниматься");
        assert!(!consume(id), "повторное скачивание по той же ссылке");
    }

    #[test]
    fn выдуманный_билет_не_принимается() {
        assert!(!consume(Uuid::new_v4()));
    }
}
