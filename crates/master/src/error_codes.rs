//! Реестр видов отказа: стабильный номер и машинный слаг.
//!
//! Файл длиннее 150 строк намеренно (см. INSTRUCTIONS §21.1): это таблица, и
//! разрезать её по файлам значит потерять единственное место, где видно все
//! занятые номера разом.
//!
//! Номер нужен человеку. Игрок или админ называет «ошибка 1203», и этого хватает,
//! чтобы найти место в коде — не пересказывая текст, который зависит от языка и
//! может быть переписан.
//!
//! **Номер не меняется никогда.** Слаг переименовать можно, номер — нет: он уже
//! уехал в чужие скриншоты и сообщения в поддержку. Освободившийся номер тоже не
//! переиспользуется, иначе старый скриншот начнёт означать другое.
//!
//! Дробность важнее краткости. Один `bad_request` на полторы сотни разных причин
//! говорит ровно столько же, сколько «что-то пошло не так», — поэтому каждый
//! отказ, который человек может увидеть и не понять, получает свой номер.
//!
//! | Номера | Про что |
//! |---|---|
//! | 1000–1099 | доступ: кто ты и что тебе можно |
//! | 1100–1199 | запрос: форма и содержимое |
//! | 1200–1299 | файлы и загрузки |
//! | 1300–1399 | состояние: чего нет, что занято, кто не на связи |
//! | 1400–1499 | внешние источники и наша настройка |
//! | 1900–1999 | наша поломка |

/// Вид отказа. Номер и слаг заданы одной строкой реестра и разъехаться не могут.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ErrorCode {
    pub number: u16,
    pub slug: &'static str,
}

macro_rules! codes {
    ($($(#[$doc:meta])* $name:ident = $number:literal, $slug:literal;)*) => {
        $($(#[$doc])* pub const $name: ErrorCode = ErrorCode { number: $number, slug: $slug };)*

        /// Весь реестр — для проверок и для справочника в документации.
        pub const ALL: &[ErrorCode] = &[$($name),*];
    };
}

codes! {
    // ── 1000–1099 доступ ────────────────────────────────────────────────────
    /// Токена нет или он не опознан.
    UNAUTHORIZED = 1001, "unauthorized";
    /// Опознан, но права не те.
    FORBIDDEN = 1002, "forbidden";
    /// Нужно подтвердить, что это ты, — passkey или код восстановления.
    STEP_UP_REQUIRED = 1003, "step_up_required";
    /// Слишком часто; когда повторять — в `Retry-After`.
    RATE_LIMITED = 1004, "rate_limited";
    /// Аккаунт заблокирован.
    BANNED = 1005, "banned";
    /// Сессия истекла или отозвана.
    SESSION_EXPIRED = 1006, "session_expired";
    /// Одноразовый код или challenge входа неверен либо протух.
    LOGIN_CHALLENGE_INVALID = 1007, "login_challenge_invalid";
    /// Действие требует живого пользователя, а пришёл админ-токен.
    USER_REQUIRED = 1008, "user_required";
    /// Root-аккаунт трогать нельзя.
    ROOT_PROTECTED = 1009, "root_protected";
    /// OAuth2: приложения с таким `client_id` нет.
    OAUTH_UNKNOWN_CLIENT = 1010, "oauth_unknown_client";
    /// OAuth2: адрес возврата не зарегистрирован у приложения.
    OAUTH_BAD_REDIRECT = 1011, "oauth_bad_redirect";
    /// OAuth2: scope неизвестен или приложению не разрешён.
    OAUTH_BAD_SCOPE = 1012, "oauth_bad_scope";

    // ── 1100–1199 запрос ────────────────────────────────────────────────────
    /// Запрос не разобран или значение не годится без привязки к полю.
    BAD_REQUEST = 1101, "bad_request";
    /// Форма не прошла проверку; что именно — в `details`.
    VALIDATION = 1102, "validation_error";
    /// Идентификатор не разобран: ждали UUID или число.
    BAD_IDENTIFIER = 1103, "bad_identifier";
    /// Значение вне допустимого набора.
    BAD_ENUM = 1104, "bad_enum";
    /// Срок или количество должны быть положительными.
    BAD_DURATION = 1105, "bad_duration";

    // ── 1200–1299 файлы и загрузки ──────────────────────────────────────────
    /// В multipart нет обязательного поля с файлом.
    UPLOAD_FIELD_MISSING = 1201, "upload_field_missing";
    /// Файл не того формата: ждали картинку, архив или текст.
    UPLOAD_BAD_FORMAT = 1202, "upload_bad_format";
    /// Файл больше допустимого.
    UPLOAD_TOO_LARGE = 1203, "upload_too_large";
    /// Путь выходит за корень сборки.
    PATH_ESCAPES_BUILD = 1204, "path_escapes_build";
    /// Архив не разобран или пуст.
    ARCHIVE_BROKEN = 1205, "archive_broken";
    /// Скачанное не сошлось по контрольной сумме.
    CHECKSUM_MISMATCH = 1206, "checksum_mismatch";

    // ── 1300–1399 состояние ─────────────────────────────────────────────────
    /// Запрошенного нет.
    NOT_FOUND = 1301, "not_found";
    /// Состояние разошлось с тем, что предполагал запрос.
    CONFLICT = 1302, "conflict";
    /// Нарушен уникальный индекс: такое уже заведено.
    ALREADY_EXISTS = 1303, "already_exists";
    /// Дело уже взял другой модератор.
    ALREADY_CLAIMED = 1304, "already_claimed";
    /// По делу уже вынесен вердикт, второй не ставится.
    CASE_NOT_OPEN = 1305, "case_not_open";
    /// Мастер не знает такого игрока.
    PLAYER_NOT_FOUND = 1306, "player_not_found";
    /// Лаунчер игрока не на связи.
    LAUNCHER_OFFLINE = 1307, "launcher_offline";
    /// Враппер игрового сервера не подключён.
    WRAPPER_OFFLINE = 1308, "wrapper_offline";
    /// Агент на игровом сервере не на связи.
    AGENT_OFFLINE = 1309, "agent_offline";
    /// У сервера нет опубликованной сборки.
    NO_PUBLISHED_BUILD = 1310, "no_published_build";
    /// Наказание уже снято.
    ALREADY_LIFTED = 1311, "already_lifted";

    // ── 1400–1499 внешние источники и настройка ─────────────────────────────
    /// Внешний источник не ответил или ответил ошибкой.
    UPSTREAM_FAILED = 1401, "upstream_failed";
    /// Подходящей версии мода не нашлось.
    NO_COMPATIBLE_VERSION = 1402, "no_compatible_version";
    /// Автор мода запретил стороннюю раздачу.
    NOT_DISTRIBUTABLE = 1403, "not_distributable";
    /// Не задана переменная окружения или настройка инстанса.
    NOT_CONFIGURED = 1404, "not_configured";

    // ── 1900–1999 наша поломка ──────────────────────────────────────────────
    /// Наша поломка. Подробности — только в логе.
    INTERNAL = 1901, "internal_error";
}

