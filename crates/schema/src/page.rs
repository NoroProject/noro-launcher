//! Конверт списочного ответа.
//!
//! Живёт в `schema`, а не в мастере, потому что читают его сразу трое: админка,
//! лаунчер (панель разбора в игре) и CLI. Пока форма была объявлена только на
//! стороне мастера, каждый клиент угадывал её у себя — и разошлись бы они
//! молча, на первом же поле, которое кто-то забыл добавить.

use serde::{Deserialize, Serialize};

/// Страница списка: то, что поместилось, и сколько всего подходит под запрос.
///
/// `total` считается по тому же условию, что и выборка. Без него клиент не
/// отличает «это всё» от «показано первое из» — а списки, отданные голым
/// массивом с зашитым лимитом, именно так и терялись.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Page<T> {
    pub items: Vec<T>,
    pub total: i64,
}

impl<T> Page<T> {
    pub fn new(items: Vec<T>, total: i64) -> Self {
        Self { items, total }
    }

    /// Когда пагинации нет по существу — список короткий и отдаётся целиком.
    /// Форма ответа при этом та же, поэтому клиент не различает случаи.
    pub fn whole(items: Vec<T>) -> Self {
        let total = items.len() as i64;
        Self { items, total }
    }

    /// Переложить в другой тип, сохранив счётчик: строки БД → модели ответа.
    pub fn map<U>(self, f: impl FnMut(T) -> U) -> Page<U> {
        Page {
            items: self.items.into_iter().map(f).collect(),
            total: self.total,
        }
    }
}
