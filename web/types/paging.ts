/**
 * Единая форма списочного ответа мастера.
 *
 * `total` — сколько всего подходит под запрос, а не сколько приехало в `items`.
 * Без него нельзя ни показать номера страниц, ни понять, что список кончился.
 */
export interface Page<T> {
    items: T[]
    total: number
}

export const EMPTY_PAGE = { items: [], total: 0 }
