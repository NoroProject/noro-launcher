<script setup lang="ts">
// Язык страницы — выбранный, а не вшитый в конфиг: по нему браузер решает,
// предлагать ли перевод, и как читать текст экранным диктором.
const { locale } = useT()
useHead({ htmlAttrs: { lang: locale } })

/**
 * Тема всегда тёмная — светлой версии у интерфейса нет.
 *
 * Одного `colorMode.preference` в конфиге мало: модуль хранит выбор в браузере,
 * и сохранённый там `light` (со времён, когда тема шла за системной) перебивает
 * настройку. Пока переключателя темы нет, значение перезаписывается на каждой
 * загрузке — иначе окна Nuxt UI приезжают белыми поверх тёмной страницы.
 */
const colorMode = useColorMode()
colorMode.preference = 'dark'
</script>

<template>
  <UApp>
    <!-- Фон один на всё приложение, а не на страницу: слой живёт выше
         маршрутов, поэтому переход между разделами не перезапускает шейдер и
         снег не «моргает». Рисуется только в браузере — WebGL на сервере нет. -->
    <ClientOnly>
      <!-- Яркость оставлена на единице: приглушать надо прозрачностью слоя, а
           не `brightness` — тусклая снежинка тускнеет вместе с альфой и просто
           тает вдали. Пиксель мельче исходных 200: крупные блоки на этом фоне
           выглядели мусором, а не ретро. -->
      <div class="pointer-events-none fixed inset-0 -z-[1] opacity-60">
        <PixelSnow
          color="#ffffff"
          :density="0.25"
          :speed="0.7"
          :brightness="1"
          :pixel-resolution="320"
          :depth-fade="5"
          :direction="115"
        />
      </div>
    </ClientOnly>

    <NuxtLayout>
      <NuxtPage />
    </NuxtLayout>
  </UApp>
</template>
