package dev.noro.agent.core;

import java.util.Collection;
import java.util.List;
import java.util.UUID;

/**
 * Единственное, что heartbeat'у нужно знать про конкретную платформу.
 *
 * <p>Paper, NeoForge и Fabric считают онлайн по-разному, поэтому цифры приходят
 * снаружи, а вся работа с сетью и расписанием остаётся в core.
 */
public interface ServerStatus {

    int online();

    int maxPlayers();

    /** Ядро и его версия, например {@code "Paper 1.21.1"} — видно в админке. */
    String version();

    /**
     * Кто сейчас в игре, поимённо.
     *
     * <p>Это и есть источник истины о составе: события входа и выхода едут по
     * каналу, который рвётся, и без полного списка раз в интервал у мастера
     * копились бы вечно живые игроки.
     */
    Collection<UUID> players();

    /**
     * Скрытые ванишем. Отдельно от {@link #players()}: в публичном числе их
     * нет, а в составе для стаффа и в сессиях — есть.
     *
     * <p>По умолчанию пусто: ваниш появляется не на всех платформах сразу, а
     * до тех пор скрывать некого.
     */
    default Collection<UUID> vanished() {
        return List.of();
    }

    /**
     * Тиков в секунду по счётчику агента. {@code null} — платформа тики не
     * считает либо первое окно ещё не набралось.
     */
    default Double tps() {
        return null;
    }

    /**
     * Миллисекунд работы на тик. {@code null} на платформах, где известен
     * только конец тика: средним по циклу подменять реальное время работы
     * нельзя — у здорового сервера цикл всегда 50 мс, и такое «mspt» не
     * добавило бы к TPS ничего.
     */
    default Double mspt() {
        return null;
    }

    /**
     * Сколько секунд не двигался игровой поток. Ноль — сервер тикает либо ещё
     * не начинал.
     */
    default int stalledSeconds() {
        return 0;
    }
}
