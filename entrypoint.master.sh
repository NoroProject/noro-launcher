#!/bin/sh
# Данные в том заливают руками — rsync с ноутбука, распаковка бэкапа — и владелец
# приезжает чужой (uid хоста), после чего мастер под uid 10001 не может писать в
# стор. Поэтому стартуем от root, приводим владельца к noro и только потом
# сбрасываем права. Если контейнер и так запущен под непривилегированным
# пользователем (docker run --user), chown невозможен — просто запускаем мастер.
set -e

if [ "$(id -u)" = "0" ]; then
    chown -R noro:noro "$NORO_DATA_DIR"
    exec setpriv --reuid=10001 --regid=10001 --init-groups "$@"
fi

exec "$@"
